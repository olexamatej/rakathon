#!/usr/bin/env bash
# One-time Antigravity setup for local Gemini photo transcription (PillGaze).
#
# Installs CLIProxyAPI, writes ~/.cli-proxy-api/config.yaml with a fresh client
# key, signs in with a Google/Antigravity account (OAuth) and prints the .env
# values this repository's interaction engine expects. Nothing in the
# repository is modified. Re-run it after the OAuth token expires.
#
# Usage: scripts/setup-antigravity-proxy.sh [--no-login]
set -euo pipefail

REPO=router-for-me/CLIProxyAPI
INSTALL_DIR="$HOME/.local/bin"
BIN="$INSTALL_DIR/cli-proxy-api"
CONFIG_DIR="$HOME/.cli-proxy-api"
CONFIG="$CONFIG_DIR/config.yaml"
LOGIN=1

for arg in "$@"; do
  case "$arg" in
    --no-login) LOGIN=0 ;;
    -h|--help) sed -n '2,10p' "$0"; exit 0 ;;
    *) echo "Unknown argument: $arg (see --help)" >&2; exit 2 ;;
  esac
done

need() { command -v "$1" >/dev/null 2>&1 || { echo "Missing required command: $1" >&2; exit 1; }; }
need curl
need tar
need awk
need sed

case "$(uname -s)" in
  Linux) os=linux ;;
  Darwin) os=darwin ;;
  *) echo "Unsupported OS: $(uname -s); use the manual setup in docs/gemini-transcription.md" >&2; exit 1 ;;
esac
case "$(uname -m)" in
  x86_64 | amd64) arch=amd64 ;;
  arm64 | aarch64) arch=aarch64 ;;
  *) echo "Unsupported architecture: $(uname -m)" >&2; exit 1 ;;
esac

mkdir -p "$INSTALL_DIR" "$CONFIG_DIR"

if [ -x "$BIN" ]; then
  echo "Using existing $BIN"
else
  tag=$(curl -fsSL "https://api.github.com/repos/$REPO/releases/latest" |
    sed -n 's/.*"tag_name": *"\([^"]*\)".*/\1/p' | head -n1)
  [ -n "$tag" ] || { echo "Could not resolve the latest CLIProxyAPI release." >&2; exit 1; }
  version=${tag#v}
  asset="CLIProxyAPI_${version}_${os}_${arch}.tar.gz"
  base="https://github.com/$REPO/releases/download/$tag"
  tmp=$(mktemp -d)
  trap 'rm -rf "$tmp"' EXIT
  echo "Downloading $asset ($tag)"
  curl -fsSL -o "$tmp/$asset" "$base/$asset"
  if curl -fsSL -o "$tmp/checksums.txt" "$base/checksums.txt" &&
    grep -q " $asset\$" "$tmp/checksums.txt"; then
    sum=sha256sum
    command -v sha256sum >/dev/null 2>&1 || sum="shasum -a 256"
    (cd "$tmp" && grep " $asset\$" checksums.txt | $sum -c -) ||
      { echo "Checksum verification failed." >&2; exit 1; }
  else
    echo "Warning: no checksum entry for $asset; continuing." >&2
  fi
  tar -xzf "$tmp/$asset" -C "$tmp"
  bin_path=$(find "$tmp" -type f -name cli-proxy-api | head -n1)
  [ -n "$bin_path" ] || { echo "cli-proxy-api binary not found in $asset" >&2; exit 1; }
  cp "$bin_path" "$BIN"
  chmod 0755 "$BIN"
  echo "Installed $BIN"
fi

if [ -f "$CONFIG" ]; then
  echo "Keeping existing $CONFIG"
else
  if command -v openssl >/dev/null 2>&1; then
    client_key=$(openssl rand -hex 24)
  else
    client_key=$(od -An -N24 -tx1 /dev/urandom | tr -d ' \n')
  fi
  cat >"$CONFIG" <<EOF
# Local CLIProxyAPI for PillGaze photo transcription. Generated by
# scripts/setup-antigravity-proxy.sh. Upstream: Antigravity OAuth
# (agy subscription). Client auth: x-goog-api-key.
config-version: 8

server:
  host: "127.0.0.1"
  port: 8317

access:
  api-keys:
    - "$client_key"

oauth:
  auth-dir: "~/.cli-proxy-api"
  providers:
    antigravity:
      antigravity-credits: true
EOF
  chmod 600 "$CONFIG"
  echo "Wrote $CONFIG"
fi

client_key=$(awk '/^[[:space:]]*api-keys:/{getline; gsub(/[[:space:]"-]/,""); print; exit}' "$CONFIG")

if [ "$LOGIN" -eq 1 ]; then
  echo
  echo "Signing in to Antigravity: a browser window or a URL will open."
  "$BIN" -config "$CONFIG" -antigravity-login
fi

cat <<EOF

Setup complete.

Add the binary to PATH for this repository's npm scripts:
  export PATH="$INSTALL_DIR:\$PATH"

Then, in the repository root:
  1. Put these values in .env (choose a model from step 4 if needed):
       GEMINI_API_BASE=http://127.0.0.1:8317/v1beta
       GEMINI_API_KEY=$client_key
       GEMINI_MODEL=gemini-3.1-flash-image
  2. Start the proxy:  npm run proxy
  3. Start the engine: npm run engine
  4. List available models:
       curl -s -H "x-goog-api-key: $client_key" http://127.0.0.1:8317/v1beta/models

If the proxy later returns 401, re-run this script to refresh the login.
EOF
